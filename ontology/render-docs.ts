// Generates docs/ontology.md from schema.ts. `npm run docs:ontology` rewrites it; a test keeps it in sync.
import { ACTION_NAMES, actionTypes, functionTypes, LINK_TYPE_NAMES, linkTypes, markingTypes, OBJECT_TYPE_NAMES, objectTypes, ROLES } from './schema.ts';
import type { ActionTypeDef, LinkTypeDef, ObjectTypeDef, PropertyDef } from './schema.ts';

const code = (s: string) => `\`${s}\``;
const cell = (s: string) => s.replace(/\|/g, '/').replace(/\n/g, ' ');

function propType(d: PropertyDef): string {
  const t = d.type === 'enum' ? `enum(${d.values?.join(' / ')})` : d.type;
  const ref = d.refTypes ? ` -> ${d.refTypes.join('|')}` : '';
  const range = d.min !== undefined ? ` [${d.min}..${d.max}]` : '';
  return `${t}${ref}${range}`;
}

const propTable = (props: Record<string, PropertyDef>) =>
  ['| Property | Type | Required | Note |', '|---|---|---|---|',
    ...Object.entries(props).map(([k, d]) => `| ${code(k)} | ${cell(propType(d))} | ${d.required ? 'yes' : ''} | ${cell(d.note ?? '')} |`)].join('\n');

export function renderOntologyDoc(): string {
  const L: string[] = [];
  L.push('# Ontology reference', '',
    '<!-- Generated by `npm run docs:ontology` from ontology/schema.ts. Do not edit by hand; tests fail if this file drifts. -->', '',
    'Terms follow Palantir Foundry: object types, link types, action types, functions, markings. Every record in the sample world is synthetic. Article numbers and bill numbers are invented.', '',
    `Every object also has ${['id', 'type', 'markings', 'synthetic'].map(code).join(', ')}, and may carry ${code('provenance')}. Real public records collected by \`ingest/\` are \`Signal\` and \`Evidence\` objects with provenance \`public\`, \`synthetic: false\` and the official https link; every other object, people and the whole client layer included, is synthetic.`, '');

  L.push('## Roles', '', ROLES.map(code).join(', '), '');

  L.push('## Markings', '', '| Marking | Meaning |', '|---|---|', ...markingTypes.map((m) => `| ${code(m.name)} | ${cell(m.description)} |`), '');

  L.push('## Object types', '');
  for (const name of OBJECT_TYPE_NAMES) {
    const def = objectTypes[name] as ObjectTypeDef;
    L.push(`### ${code(name)}`, '', `${def.layer === 'public' ? 'Public layer' : 'Client layer'}. ${def.description}`, '', propTable(def.properties), '');
  }

  L.push('## Link types', '',
    'Cardinality reads from source to target. `requiredFrom` / `requiredTo` list object types that must take part in at least one such link.', '',
    '| Link | From | To | Cardinality | Layer | Evidence required | Required for | Properties |', '|---|---|---|---|---|---|---|---|');
  for (const name of LINK_TYPE_NAMES) {
    const d = linkTypes[name] as LinkTypeDef;
    const req = [...(d.requiredFrom ?? []).map((t) => `${t} (from)`), ...(d.requiredTo ?? []).map((t) => `${t} (to)`)].join(', ');
    const props = Object.entries(d.props ?? {}).map(([k, p]) => `${k}: ${propType(p)}`).join('; ');
    L.push(`| ${code(name)} | ${d.from.join(', ')} | ${d.to.join(', ')} | ${d.cardinality} | ${d.layer} | ${d.evidenceRequired ? 'yes' : 'no'} | ${req} | ${cell(props)} |`);
  }
  L.push('');

  L.push('## Action types', '', 'Actions are the only way to change state. Each call is checked for role, parameters (every referenced object must be visible to the caller, and one call may name objects from at most one client layer) and preconditions, then executed or held for approval. Every attempt, including refusals, is appended to the audit log.', '');
  for (const name of ACTION_NAMES) {
    const d = actionTypes[name] as ActionTypeDef;
    L.push(`### ${code(name)}`, '', d.description, '',
      `- Allowed roles: ${d.allowedRoles.map(code).join(', ')}`,
      `- Approval: ${d.requiresApproval ? `required from ${code(d.approverRole!)} before it runs` : 'not required'}`);
    for (const p of d.preconditions ?? []) L.push(`- Precondition: ${code(p.param)}.${p.field} in [${p.in.join(', ')}] (${p.message})`);
    for (const c of d.constraints ?? []) L.push(`- Rule: ${c}`);
    for (const s of d.sideEffects) L.push(`- Effect: ${s}`);
    L.push('', propTable(d.params), '');
  }

  L.push('## Permission matrix', '', 'yes = may run it; approval = may request it, the principal must approve; - = denied.', '',
    `| Action | ${ROLES.join(' | ')} |`, `|---|${ROLES.map(() => '---').join('|')}|`);
  for (const name of ACTION_NAMES) {
    const d = actionTypes[name] as ActionTypeDef;
    const cells = ROLES.map((r) => (!d.allowedRoles.includes(r) ? '-' : d.requiresApproval && r !== d.approverRole ? 'approval' : 'yes'));
    L.push(`| ${code(name)} | ${cells.join(' | ')} |`);
  }
  L.push('');

  L.push('## Functions', '', 'Deterministic and read-only. Each takes a `view`, the caller-filtered read handle from `store.as(ctx)`.', '',
    '| Function | Signature | What it returns |', '|---|---|---|', ...functionTypes.map((f) => `| ${code(f.name)} | ${code(f.signature)} | ${cell(f.description)} |`), '');
  return L.join('\n');
}

// CLI: node:fs is imported lazily so this module stays safe to bundle for the browser.
if (import.meta.main) {
  const { writeFileSync } = await import('node:fs');
  writeFileSync(new URL('../docs/ontology.md', import.meta.url), renderOntologyDoc());
  console.log('wrote docs/ontology.md');
}
